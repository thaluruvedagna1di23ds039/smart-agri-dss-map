"""Crop-yield model: scikit-learn RandomForest.

IMPORTANT (honesty note): no real farm-yield dataset is bundled, because those
datasets carry their own licences. By default the model is trained on a
synthetic dataset generated by `potential()` below, an original rule-based
agronomic response function with random noise. So the model demonstrates the
full ML pipeline, but its numbers are *indicative*, not field-validated.
To use real data, run:  python train.py --csv your_data.csv
(columns: temp,rain,humidity,ph,nitrogen,soc,clay,crop,yield_t_ha)
"""
import json
from pathlib import Path

import joblib
import numpy as np

from .crops import CROPS, CROP_NAMES

FEATURES = ["temp", "rain", "humidity", "ph", "nitrogen", "soc", "clay"]
MODEL_DIR = Path(__file__).resolve().parent.parent / "models"
MODEL_PATH = MODEL_DIR / "yield_model.joblib"
METRICS_PATH = MODEL_DIR / "metrics.json"


def _g(x, mu, s):
    return np.exp(-0.5 * ((x - mu) / s) ** 2)


def potential(X, crop):
    """Relative yield (0-1) of `crop` for feature matrix X (rule-based)."""
    c = CROPS[crop]
    t, r, h, ph, n, soc, clay = (X[:, i] for i in range(7))
    suit = _g(t, *c["t"]) * _g(r, *c["r"]) * _g(ph, *c["ph"])
    hum = _g(h, 65, 30) ** 0.3
    nf = 0.6 + 0.4 * np.clip(n / c["n_opt"], 0, 1)
    socf = 0.7 + 0.3 * np.clip(soc / 15.0, 0, 1)
    clayf = _g(clay, 30, 25) ** 0.2
    return suit * hum * nf * socf * clayf


def _onehot(idx, n=len(CROP_NAMES)):
    m = np.zeros((len(idx), n))
    m[np.arange(len(idx)), idx] = 1
    return m


def synthetic_dataset(per_crop=2500, seed=42):
    rng = np.random.default_rng(seed)
    Xs, ys, cs = [], [], []
    for ci, name in enumerate(CROP_NAMES):
        X = np.column_stack([
            rng.uniform(8, 35, per_crop),      # temp
            rng.uniform(200, 3000, per_crop),  # rain
            rng.uniform(25, 95, per_crop),     # humidity
            rng.uniform(4.5, 8.5, per_crop),   # pH
            rng.uniform(0.2, 3.0, per_crop),   # nitrogen g/kg
            rng.uniform(3, 40, per_crop),      # soc g/kg
            rng.uniform(5, 60, per_crop),      # clay %
        ])
        y = np.clip(potential(X, name) * rng.lognormal(0, 0.08, per_crop), 0, 1)
        Xs.append(X); ys.append(y); cs.append(np.full(per_crop, ci))
    return np.vstack(Xs), np.concatenate(ys), np.concatenate(cs)


def train(csv_path=None):
    from sklearn.ensemble import RandomForestRegressor
    from sklearn.metrics import mean_absolute_error, r2_score
    from sklearn.model_selection import train_test_split

    if csv_path:
        import pandas as pd
        df = pd.read_csv(csv_path)
        df = df[df["crop"].isin(CROP_NAMES)].dropna(subset=FEATURES + ["yield_t_ha"])
        X = df[FEATURES].to_numpy(float)
        cidx = df["crop"].map({n: i for i, n in enumerate(CROP_NAMES)}).to_numpy(int)
        base = df["crop"].map({n: CROPS[n]["base"] for n in CROP_NAMES}).to_numpy(float)
        y = np.clip(df["yield_t_ha"].to_numpy(float) / base, 0, 1.5)
        source = f"real data: {Path(csv_path).name}"
    else:
        X, y, cidx = synthetic_dataset()
        source = "synthetic agronomic-rule dataset"

    F = np.hstack([X, _onehot(cidx)])
    Ftr, Fte, ytr, yte = train_test_split(F, y, test_size=0.2, random_state=1)
    model = RandomForestRegressor(n_estimators=150, min_samples_leaf=3,
                                  n_jobs=-1, random_state=1)
    model.fit(Ftr, ytr)
    pred = model.predict(Fte)
    metrics = dict(r2=round(float(r2_score(yte, pred)), 4),
                   mae_relative=round(float(mean_absolute_error(yte, pred)), 4),
                   rows=int(len(y)), data_source=source)
    MODEL_DIR.mkdir(exist_ok=True)
    joblib.dump(model, MODEL_PATH, compress=3)
    METRICS_PATH.write_text(json.dumps(metrics, indent=2))
    return metrics


_model = None


def get_model():
    global _model
    if _model is None:
        if not MODEL_PATH.exists():
            train()
        _model = joblib.load(MODEL_PATH)
    return _model


def get_metrics():
    if not METRICS_PATH.exists():
        get_model()
    return json.loads(METRICS_PATH.read_text())


def predict_all(inputs):
    """Predict relative yield for every crop at this location.

    Returns list of dicts sorted by suitability (best first).
    """
    x = np.array([[inputs[f] for f in FEATURES]], dtype=float)
    X = np.repeat(x, len(CROP_NAMES), axis=0)
    F = np.hstack([X, np.eye(len(CROP_NAMES))])
    rel = np.clip(get_model().predict(F), 0, 1.5)
    rows = []
    for name, rv in zip(CROP_NAMES, rel):
        rows.append(dict(crop=name,
                         suitability_pct=round(float(rv) * 100, 1),
                         yield_t_ha=round(float(rv) * CROPS[name]["base"], 2)))
    rows.sort(key=lambda d: d["suitability_pct"], reverse=True)
    return rows
